#!/usr/bin/env node
/**
 * Emits `<outDir>/firebase-messaging-sw.js` — the service worker that receives BACKGROUND web-push
 * messages (a push that arrives while the tab is closed). It is separate from the app's own `/sw.js`
 * (offline shell + self-update) on purpose: Firebase's SDK expects to own a worker at a fixed path, and
 * mixing the two behaviours in one file is how a caching worker starts eating push events.
 *
 * WHY GENERATED, NOT COMMITTED. The worker needs the project's PUBLIC Firebase config baked in
 * (apiKey/projectId/senderId/appId — all public, like the Supabase anon key). Those live in the Vite
 * mode env (`VITE_FIREBASE_*`, derived from workers/wrangler.toml), so the worker is written from the
 * same source at build time rather than duplicating the values into a tracked file that could drift.
 *
 * WHEN UNCONFIGURED (the default today) this writes nothing and removes any stale worker, so an
 * unconfigured build ships no dead push worker and the app cleanly degrades to the in-app inbox.
 *
 * Called by `scripts/build-web.mjs` after the PWA step; also runnable directly:
 *   node scripts/build-firebase-sw.mjs --out-dir dist/web --mode production
 */

import fs from "node:fs";
import path from "node:path";
import process from "node:process";

import { REPO_ROOT } from "../tools/vite-shared.ts";

// The compat SDK version the importScripts() lines pull from gstatic. Pinned so the worker is
// reproducible and does not silently follow a major bump.
const FIREBASE_SDK_VERSION = "10.14.1";

/** Read VITE_FIREBASE_* for a mode without a full Vite run: shell env wins, then `.env.<mode>`, then `.env`. */
export async function firebaseConfigForMode(mode) {
  const { loadEnv } = await import("vite");
  // loadEnv merges process.env over the mode files, matching how the browser build resolves them.
  const env = mode ? loadEnv(mode, REPO_ROOT, "VITE_") : { ...process.env };
  const pick = (name) => String(env[name] ?? process.env[name] ?? "").trim();
  const apiKey = pick("VITE_FIREBASE_API_KEY");
  const projectId = pick("VITE_FIREBASE_PROJECT_ID");
  const messagingSenderId = pick("VITE_FIREBASE_MESSAGING_SENDER_ID");
  const appId = pick("VITE_FIREBASE_APP_ID");
  if (!apiKey || !projectId || !messagingSenderId || !appId) return null;
  const authDomain = pick("VITE_FIREBASE_AUTH_DOMAIN") || `${projectId}.firebaseapp.com`;
  const storageBucket = pick("VITE_FIREBASE_STORAGE_BUCKET") || `${projectId}.appspot.com`;
  return { apiKey, authDomain, projectId, storageBucket, messagingSenderId, appId };
}

function render(config) {
  // A compat-SDK worker: importScripts + firebase.initializeApp + onBackgroundMessage. `data.link` is the
  // deep link the Worker set (workers/src/services/fcm.ts → fcmOptions.link); the notificationclick handler
  // focuses an existing tab or opens it there.
  return `/* GENERATED by scripts/build-firebase-sw.mjs — do not edit. Firebase background-push worker. */
importScripts('https://www.gstatic.com/firebasejs/${FIREBASE_SDK_VERSION}/firebase-app-compat.js');
importScripts('https://www.gstatic.com/firebasejs/${FIREBASE_SDK_VERSION}/firebase-messaging-compat.js');

firebase.initializeApp(${JSON.stringify(config, null, 2)});

const messaging = firebase.messaging();

messaging.onBackgroundMessage(function (payload) {
  var n = (payload && payload.notification) || {};
  var data = (payload && payload.data) || {};
  var title = n.title || 'KickLive';
  self.registration.showNotification(title, {
    body: n.body || '',
    icon: '/brand/brand-icon-512.png',
    badge: '/brand/brand-icon-192.png',
    tag: 'kicklive-' + (data.matchId || 'general'),
    data: { link: data.link || '/' },
  });
});

self.addEventListener('notificationclick', function (event) {
  event.notification.close();
  var link = (event.notification.data && event.notification.data.link) || '/';
  event.waitUntil(
    self.clients.matchAll({ type: 'window', includeUncontrolled: true }).then(function (clients) {
      for (var i = 0; i < clients.length; i++) {
        var c = clients[i];
        if ('focus' in c) {
          try { c.navigate(link); } catch (e) { /* older browsers: focus only */ }
          return c.focus();
        }
      }
      if (self.clients.openWindow) return self.clients.openWindow(link);
    }),
  );
});
`;
}

export async function buildFirebaseSw({ outDir, mode, log = console.log } = {}) {
  const absOut = path.resolve(outDir);
  const target = path.join(absOut, "firebase-messaging-sw.js");
  const config = await firebaseConfigForMode(mode);
  if (!config) {
    if (fs.existsSync(target)) fs.rmSync(target);
    log("build-firebase-sw: no VITE_FIREBASE_* config for this build — skipped (push degrades to the in-app inbox)");
    return { written: false };
  }
  if (!fs.existsSync(absOut)) throw new Error(`build-firebase-sw: out dir does not exist: ${absOut}`);
  fs.writeFileSync(target, render(config));
  log(`build-firebase-sw: ${path.relative(REPO_ROOT, target)} for project ${config.projectId}`);
  return { written: true, projectId: config.projectId };
}

const invokedDirectly = process.argv[1] && path.resolve(process.argv[1]).endsWith("build-firebase-sw.mjs");
if (invokedDirectly) {
  const args = process.argv.slice(2);
  const outIdx = args.indexOf("--out-dir");
  const outDir = outIdx >= 0 ? args[outIdx + 1] : "dist/web";
  const modeIdx = args.indexOf("--mode");
  const mode = modeIdx >= 0 ? args[modeIdx + 1] : undefined;
  await buildFirebaseSw({ outDir, mode });
}
